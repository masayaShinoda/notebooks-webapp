# Security
# https://docs.djangoproject.com/en/6.0/howto/deployment/checklist/
#
# The app runs behind nginx, which terminates TLS and proxies over a unix
# socket. Django therefore only ever sees plain HTTP on the wire and has to be
# told how to recognise an originally-HTTPS request.
#
# WARNING: SECURE_PROXY_SSL_HEADER and nginx's `proxy_set_header
# X-Forwarded-Proto $scheme;` are a matched pair. With SECURE_SSL_REDIRECT on
# but that header missing, Django never believes the request was secure and
# redirects forever.
